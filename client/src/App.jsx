import { BrowserRouter, Routes, Route, Navigate } from 'react-router-dom';
import { Toaster } from 'react-hot-toast';
import Signup from './pages/Signup';
import Login from './pages/Login';
import Dashboard from './pages/Dashboard';
import ProtectedRoute from './components/ProtectedRoute';
import Profile from './pages/Profile'; // Import the Profile page
import Notes from './pages/Notes'; // Import the Notes page
import Navbar from './components/Navbar'; // Import the Navbar component 
import Chat from './pages/Chat'; // Import the Chat page
import Resources from './pages/Resources'; // Import the Resources page
import Calendar from './pages/Calendar'; // Import the Calendar page
import Landing from './pages/Landing'; // Import the Landing page
import useAuthStore from './store/authStore';

function App() {
  const token = useAuthStore((state) => state.token);

  return (
    <BrowserRouter>
      <Toaster position="top-center" />

      <Navbar /> {/* Render the Navbar at the top of every page */}

      {/* A container for the main content */}
      <div style={{ padding: '2rem 0'}}>
        <Routes>
          <Route path="/" element={<Landing />} />
          <Route path="/signup" element={token ? <Navigate to="/dashboard" replace /> : <Signup />} />
          <Route path="/register" element={<Navigate to="/signup" replace />} />
          <Route path="/login" element={token ? <Navigate to="/dashboard" replace /> : <Login />} />

          {/* we wrap the Dashboard route in our ProtectedRoute component,
          which checks if the user has a valid token before allowing access to the Dashboard page.
            If they don't have a token, they will be redirected to the login page. */}
          <Route path="/dashboard" element={<ProtectedRoute><Dashboard /></ProtectedRoute>} />
          <Route path="/profile" element={<ProtectedRoute><Profile /></ProtectedRoute>} />
          <Route path="/notes" element={<ProtectedRoute><Notes /></ProtectedRoute>} />
          <Route path="/chat" element={<ProtectedRoute><Chat /></ProtectedRoute>} />
          <Route path="/resources" element={<ProtectedRoute><Resources /></ProtectedRoute>} />
          <Route path="/calendar" element={<ProtectedRoute><Calendar /></ProtectedRoute>} />
          <Route path="*" element={<Navigate to="/" replace />} />
        </Routes>
      </div>
    </BrowserRouter>
  );
}

export default App;